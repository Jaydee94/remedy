-- The schema as the SQLite migrations 001 to 018 left it, in PostgreSQL (docs/specs/2026-10-22-postgres-only-design.md,
-- decisions 3 to 6). It is a translation of the end state, not a replay: every column a later migration added is in place,
-- in the order the SQLite end state has, and the tables that 008 and 016 rebuilt are written once. The SQLite files are kept
-- as the importer's fixture (internal/importsqlite/testdata/sqlite-migrations); the comments below say which file a part
-- comes from.
--
-- The types do not change (decision 3): timestamps are fixed-width TEXT (nine fractional digits, so string order is time
-- order), booleans are INTEGER 0 or 1, JSON is TEXT. An id of INTEGER PRIMARY KEY AUTOINCREMENT is BIGINT GENERATED BY
-- DEFAULT AS IDENTITY (decision 5): the importer inserts the old ids and then sets each sequence to the highest one, so no
-- id is given twice; a column that points at such an id is BIGINT. SQLite's REAL has eight bytes, so cost_usd is DOUBLE
-- PRECISION; a BLOB is BYTEA. A UNIQUE COLLATE NOCASE column is a unique index on lower(column) (decision 4).

-- 001, 004, 005, 006, 007, 011, rebuilt by 016. role: who the run is for. incident_id: the incident a responder run
-- diagnoses, cleared when the incident goes away (its foreign key is added after incidents, below). output: the structured
-- result as JSON. failure_reason: why a failed run failed when it was not the agent's exit code. head_sha: the commit a
-- responder run is for. automatic: Remedy started the run, not a click. mcp: the run has access to the gatekeeper.
-- cancel_requested: the maintainer cancelled it. cluster: the run was offered the cluster tools. host_count: the number of
-- host bindings at creation (deleting a host removes the binding, not the count).
CREATE TABLE runs (
  id                TEXT PRIMARY KEY,
  provider          TEXT NOT NULL,
  prompt            TEXT NOT NULL,
  status            TEXT NOT NULL CHECK (status IN ('queued', 'running', 'succeeded', 'failed')),
  exit_code         INTEGER,
  result            TEXT NOT NULL DEFAULT '',
  session_id        TEXT NOT NULL DEFAULT '',
  cost_usd          DOUBLE PRECISION NOT NULL DEFAULT 0,
  created_at        TEXT NOT NULL,
  started_at        TEXT,
  finished_at       TEXT,
  role              TEXT NOT NULL DEFAULT 'adhoc' CHECK (role IN ('adhoc', 'responder', 'learner')),
  incident_id       BIGINT,
  output            TEXT,
  failure_reason    TEXT NOT NULL DEFAULT '',
  head_sha          TEXT NOT NULL DEFAULT '',
  automatic         INTEGER NOT NULL DEFAULT 0,
  mcp               INTEGER NOT NULL DEFAULT 0,
  cancel_requested  INTEGER NOT NULL DEFAULT 0,
  last_heartbeat_at TEXT,
  cluster           INTEGER NOT NULL DEFAULT 0,
  host_count        INTEGER NOT NULL DEFAULT 0
);

CREATE INDEX runs_status_created ON runs (status, created_at);
CREATE INDEX runs_incident ON runs (incident_id);
CREATE INDEX runs_responder_created ON runs (role, automatic, created_at);

-- 001.
CREATE TABLE run_events (
  run_id     TEXT NOT NULL REFERENCES runs (id) ON DELETE CASCADE,
  seq        INTEGER NOT NULL,
  kind       TEXT NOT NULL,
  payload    TEXT NOT NULL,
  created_at TEXT NOT NULL,
  PRIMARY KEY (run_id, seq)
);

-- 002. One connection for now (the code always uses id 1, so the id is not an identity); the schema allows more.
CREATE TABLE github_connections (
  id               BIGINT PRIMARY KEY,
  token_ciphertext BYTEA NOT NULL,
  token_hint       TEXT NOT NULL,
  login            TEXT NOT NULL,
  status           TEXT NOT NULL CHECK (status IN ('ok', 'error', 'undecryptable')),
  status_detail    TEXT NOT NULL DEFAULT '',
  checked_at       TEXT NOT NULL
);

-- 002. full_name is unique ignoring case (repos_full_name_lower).
CREATE TABLE repos (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  connection_id  BIGINT NOT NULL REFERENCES github_connections (id) ON DELETE CASCADE,
  full_name      TEXT NOT NULL,
  default_branch TEXT NOT NULL,
  enabled        INTEGER NOT NULL DEFAULT 1,
  last_polled_at TEXT,
  last_error     TEXT NOT NULL DEFAULT '',
  created_at     TEXT NOT NULL
);

CREATE UNIQUE INDEX repos_full_name_lower ON repos (lower(full_name));

-- 010, 013. Machines outside the cluster that Remedy may be given a login to; the host key the machine must present is
-- pinned in the row. matchers: the rules that map an alert to the host, Alertmanager matcher syntax, one per line. name is
-- unique ignoring case (hosts_name_lower).
CREATE TABLE hosts (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name           TEXT NOT NULL,
  address        TEXT NOT NULL,
  port           INTEGER NOT NULL DEFAULT 22 CHECK (port BETWEEN 1 AND 65535),
  account        TEXT NOT NULL DEFAULT 'remedy',
  notes          TEXT NOT NULL DEFAULT '',
  docker_pattern TEXT NOT NULL DEFAULT '',
  systemd_units  TEXT NOT NULL DEFAULT '[]',
  enabled        INTEGER NOT NULL DEFAULT 1,
  pinned_key     TEXT NOT NULL DEFAULT '',
  pinned_at      TEXT,
  status         TEXT NOT NULL DEFAULT 'new'
                 CHECK (status IN ('new', 'untrusted', 'ok', 'error', 'key_changed', 'undecryptable')),
  status_detail  TEXT NOT NULL DEFAULT '',
  report         TEXT NOT NULL DEFAULT '',
  checked_at     TEXT,
  created_at     TEXT NOT NULL,
  updated_at     TEXT NOT NULL,
  matchers       TEXT NOT NULL DEFAULT ''
);

CREATE UNIQUE INDEX hosts_name_lower ON hosts (lower(name));

-- 003, 005, rebuilt by 008; 009, 013, 018. One incident per (source, key) while it is not resolved; an ignored incident keeps
-- its key, so a new failure does not open a second one. source: github, alertmanager or argocd. key: the identity inside the
-- source; for GitHub repo_id, ref and check_name joined with U+001F (store.GitHubKey). repo_id is set for GitHub incidents and
-- only for them. severity: critical, warning, info or none. auto_diagnose: whether the responder may start on its own.
-- details: the signal as bounded JSON. diagnosed_sha: the commit the stored diagnosis is about. diagnosed_at: when the stored
-- diagnosis was written. host_id: the host an alert's labels matched. resolved_while_ignored: the incident was ignored when
-- it resolved, so it stays ignored when it returns.
CREATE TABLE incidents (
  id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source                 TEXT NOT NULL DEFAULT 'github' CHECK (source IN ('github', 'alertmanager', 'argocd')),
  key                    TEXT NOT NULL,
  title                  TEXT NOT NULL DEFAULT '',
  severity               TEXT NOT NULL DEFAULT 'none' CHECK (severity IN ('critical', 'warning', 'info', 'none')),
  auto_diagnose          INTEGER NOT NULL DEFAULT 0,
  details                TEXT NOT NULL DEFAULT '{}',
  repo_id                BIGINT REFERENCES repos (id) ON DELETE CASCADE,
  ref                    TEXT NOT NULL DEFAULT '',
  ref_url                TEXT NOT NULL DEFAULT '',
  check_name             TEXT NOT NULL DEFAULT '',
  state                  TEXT NOT NULL CHECK (state IN ('open', 'diagnosing', 'diagnosed', 'resolved', 'ignored')),
  conclusion             TEXT NOT NULL,
  head_sha               TEXT NOT NULL DEFAULT '',
  check_url              TEXT NOT NULL DEFAULT '',
  occurrences            INTEGER NOT NULL DEFAULT 1,
  diagnoses              INTEGER NOT NULL DEFAULT 0,
  first_seen             TEXT NOT NULL,
  last_seen              TEXT NOT NULL,
  last_diagnosis_at      TEXT,
  resolved_at            TEXT,
  resolved_reason        TEXT NOT NULL DEFAULT '',
  diagnosis              TEXT,
  run_id                 TEXT REFERENCES runs (id) ON DELETE SET NULL,
  diagnosed_sha          TEXT NOT NULL DEFAULT '',
  diagnosed_at           TEXT,
  host_id                BIGINT REFERENCES hosts (id) ON DELETE SET NULL,
  resolved_while_ignored INTEGER NOT NULL DEFAULT 0,
  CHECK ((source = 'github') = (repo_id IS NOT NULL))
);

CREATE UNIQUE INDEX incidents_active_key ON incidents (source, key) WHERE state <> 'resolved';
CREATE INDEX incidents_state_seen ON incidents (state, last_seen);
CREATE INDEX incidents_source_state ON incidents (source, state);
CREATE INDEX incidents_host ON incidents (host_id);

-- 004: the run's incident link, now that incidents exists.
ALTER TABLE runs ADD FOREIGN KEY (incident_id) REFERENCES incidents (id) ON DELETE SET NULL;

-- 003. Append-only. The links are nulled, not cascaded, when their target is deleted: the history stays and its summary
-- still names what happened.
CREATE TABLE activity (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  at          TEXT NOT NULL,
  kind        TEXT NOT NULL,
  repo_id     BIGINT REFERENCES repos (id) ON DELETE SET NULL,
  incident_id BIGINT REFERENCES incidents (id) ON DELETE SET NULL,
  run_id      TEXT REFERENCES runs (id) ON DELETE SET NULL,
  summary     TEXT NOT NULL,
  data        TEXT NOT NULL DEFAULT '{}'
);

CREATE INDEX activity_incident ON activity (incident_id, id);

-- 006. The token of a run with gatekeeper access: only its SHA-256 is stored; revoked_at is set when the run ends.
CREATE TABLE run_tokens (
  run_id     TEXT PRIMARY KEY REFERENCES runs (id) ON DELETE CASCADE,
  token_hash BYTEA NOT NULL UNIQUE,
  created_at TEXT NOT NULL,
  revoked_at TEXT
);

-- 006, 014. One row per tool call of an agent: the audit log, and for a mutating tool the approval. The rows are never
-- deleted. (run_id, tool_use_id) identifies a call, so that a repeat of it finds the first one. decision is empty for a read
-- tool. expires_at: the deadline of an approval in an automatic run.
CREATE TABLE tool_calls (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id          TEXT NOT NULL REFERENCES runs (id) ON DELETE CASCADE,
  incident_id     BIGINT REFERENCES incidents (id) ON DELETE SET NULL,
  tool_use_id     TEXT NOT NULL,
  tool            TEXT NOT NULL,
  kind            TEXT NOT NULL CHECK (kind IN ('read', 'mutating')),
  arguments       TEXT NOT NULL DEFAULT '{}',
  status          TEXT NOT NULL CHECK (status IN ('running', 'waiting', 'succeeded', 'failed', 'denied', 'abandoned')),
  result          TEXT NOT NULL DEFAULT '',
  error           TEXT NOT NULL DEFAULT '',
  decision        TEXT NOT NULL DEFAULT '' CHECK (decision IN ('', 'pending', 'approved', 'denied', 'abandoned')),
  decision_reason TEXT NOT NULL DEFAULT '',
  decided_at      TEXT,
  created_at      TEXT NOT NULL,
  finished_at     TEXT,
  expires_at      TEXT,
  UNIQUE (run_id, tool_use_id)
);

CREATE INDEX tool_calls_decision ON tool_calls (decision, id);

-- 006. Notes that an agent run added to an incident, with the maintainer's approval.
CREATE TABLE incident_notes (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  incident_id BIGINT NOT NULL REFERENCES incidents (id) ON DELETE CASCADE,
  run_id      TEXT REFERENCES runs (id) ON DELETE SET NULL,
  note        TEXT NOT NULL,
  created_at  TEXT NOT NULL
);

CREATE INDEX incident_notes_incident ON incident_notes (incident_id, id);

-- 010. A host's credential, sealed (AES-256-GCM, bound to the host id).
CREATE TABLE host_credentials (
  host_id    BIGINT PRIMARY KEY REFERENCES hosts (id) ON DELETE CASCADE,
  kind       TEXT NOT NULL CHECK (kind IN ('key', 'password')),
  ciphertext BYTEA NOT NULL,
  hint       TEXT NOT NULL,
  public_key TEXT NOT NULL DEFAULT '',
  updated_at TEXT NOT NULL
);

-- 011. The hosts of a run, bound when the run is created.
CREATE TABLE run_hosts (
  run_id  TEXT   NOT NULL REFERENCES runs (id)  ON DELETE CASCADE,
  host_id BIGINT NOT NULL REFERENCES hosts (id) ON DELETE CASCADE,
  PRIMARY KEY (run_id, host_id)
);

CREATE INDEX run_hosts_host ON run_hosts (host_id);

-- 012 (017 only copied a row). Settings of the Setup page; value is JSON.
CREATE TABLE settings (
  key        TEXT PRIMARY KEY,
  value      TEXT NOT NULL,
  updated_at TEXT NOT NULL
);

-- 015. Skills: short Markdown notes, global (host_id NULL) or bound to one host. A proposal (state 'proposed') is invisible
-- until the maintainer confirms it; 'off' keeps a skill but hides it. run_id: the learning run that proposed it. evidence is
-- JSON. A proposal that replaces a skill has the same name in the same scope, so the unique index leaves proposals out.
CREATE TABLE skills (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  host_id      BIGINT REFERENCES hosts (id) ON DELETE CASCADE,
  name         TEXT NOT NULL,
  description  TEXT NOT NULL,
  body         TEXT NOT NULL,
  origin       TEXT NOT NULL CHECK (origin IN ('written', 'proposed')),
  state        TEXT NOT NULL CHECK (state IN ('proposed', 'active', 'off')),
  run_id       TEXT REFERENCES runs (id) ON DELETE SET NULL,
  evidence     TEXT NOT NULL DEFAULT '[]',
  replaces_id  BIGINT REFERENCES skills (id) ON DELETE SET NULL,
  created_at   TEXT NOT NULL,
  updated_at   TEXT NOT NULL,
  confirmed_at TEXT
);

CREATE UNIQUE INDEX skills_scope_name ON skills (COALESCE(host_id, 0), name) WHERE state <> 'proposed';
CREATE INDEX skills_host_state ON skills (host_id, state);
