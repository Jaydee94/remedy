// Package pgtest gives a test a Postgres of its own: a fresh schema on the server named by REMEDY_TEST_DATABASE_URL.
//
// Many tests and packages share one server, run in parallel and never see each other's tables, because each test's
// connections have a search_path that holds only the schema made for that test. The schema is dropped when the test ends.
// There is no skip: a test that needs the database and cannot reach it fails, with the instruction to start one
// (make pg-up, then . dev/pg/env.sh).
//
// The URL is a secret (it holds the password): this package never puts it in a message.
package pgtest

import (
	"context"
	"crypto/rand"
	"database/sql"
	"encoding/hex"
	"errors"
	"net/url"
	"os"
	"strings"
	"testing"
	"time"

	_ "github.com/jackc/pgx/v5/stdlib" // registers the "pgx" database/sql driver
)

// EnvURL names the variable that holds the connection URL of the test server.
const EnvURL = "REMEDY_TEST_DATABASE_URL"

const instructions = EnvURL + " is not set, and the tests need a Postgres. Start a throwaway one with `make pg-up`, then run `. dev/pg/env.sh` in your shell " +
	"(or point " + EnvURL + " at any Postgres 16 server you may create schemas in). `make test` starts one by itself when docker is available. See dev/pg/README.md."

// baseURL returns the configured URL or stops the test with the instructions.
func baseURL(tb testing.TB) string {
	tb.Helper()
	u := os.Getenv(EnvURL)
	if u == "" {
		tb.Fatal(instructions)
	}
	return u
}

// open connects to the server without any schema scoping. It never reports the URL.
func open(tb testing.TB) *sql.DB {
	tb.Helper()
	db, err := sql.Open("pgx", baseURL(tb))
	if err != nil {
		tb.Fatalf("pgtest: %s is not a usable connection string (the URL is not shown: it holds a password)", EnvURL)
	}
	db.SetMaxOpenConns(2)
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()
	if err := db.PingContext(ctx); err != nil {
		_ = db.Close()
		tb.Fatalf("pgtest: cannot reach the database named by %s: %v. Is it running? `make pg-up` starts one; see dev/pg/README.md.", EnvURL, err)
	}
	return db
}

// Admin returns a connection that is not scoped to a test schema, for tests that create their own databases or schemas.
// It is closed when the test ends.
func Admin(tb testing.TB) *sql.DB {
	tb.Helper()
	db := open(tb)
	tb.Cleanup(func() { _ = db.Close() })
	return db
}

// New makes a schema for this test and returns a DSN whose connections have it as their search_path. The schema, with
// everything in it, is dropped when the test ends (so a Store opened on the DSN should be closed by a cleanup registered
// after New: cleanups run last-in first-out).
func New(tb testing.TB) string {
	tb.Helper()
	base := baseURL(tb)
	var b [8]byte
	if _, err := rand.Read(b[:]); err != nil {
		tb.Fatalf("pgtest: no randomness: %v", err)
	}
	schema := "t_" + hex.EncodeToString(b[:])
	dsn, err := scope(base, schema)
	if err != nil {
		tb.Fatalf("pgtest: %v", err)
	}

	admin := open(tb)
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()
	_, err = admin.ExecContext(ctx, `CREATE SCHEMA `+schema)
	_ = admin.Close()
	if err != nil {
		tb.Fatalf("pgtest: cannot create schema %s: %v", schema, err)
	}

	tb.Cleanup(func() {
		db, err := sql.Open("pgx", base)
		if err != nil {
			tb.Errorf("pgtest: cannot drop schema %s", schema)
			return
		}
		defer db.Close()
		ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
		defer cancel()
		if _, err := db.ExecContext(ctx, `DROP SCHEMA IF EXISTS `+schema+` CASCADE`); err != nil {
			tb.Errorf("pgtest: cannot drop schema %s: %v", schema, err)
		}
	})
	return dsn
}

// scope adds search_path=schema to a connection string, as a URL query parameter or, for the keyword/value form, as a
// further word. pgx sends it to the server in the startup message, so every connection of a pool has it. The schema
// name is generated by this package (t_ and hex), never taken from outside.
func scope(dsn, schema string) (string, error) {
	if strings.HasPrefix(dsn, "postgres://") || strings.HasPrefix(dsn, "postgresql://") {
		u, err := url.Parse(dsn)
		if err != nil {
			// url.Error carries the URL, which holds the password: say nothing about it.
			return "", errors.New(EnvURL + " is not a valid URL (it is not shown: it holds a password)")
		}
		q := u.Query()
		q.Set("search_path", schema)
		u.RawQuery = q.Encode()
		return u.String(), nil
	}
	if strings.Contains(dsn, "://") {
		return "", errors.New(EnvURL + " must be a postgres:// URL or a key=value connection string")
	}
	return dsn + " search_path=" + schema, nil
}
